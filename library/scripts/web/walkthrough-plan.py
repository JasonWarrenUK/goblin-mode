#!/usr/bin/env python3
"""walkthrough-plan.py: build the sign-off walkthrough's shot-scraper config.

Routes × devices × open states, named by the capture rule in
asset-conventions (`<(device||viewport)?>-<route>[-<specifier>].png`, the
device prefix only when more than one device is captured), full page
(no height), one entry per capture. Open states come from the inventory
(--planned) and from open-states.ts discovery (--states); a discovered
state the inventory did not name is kept and marked unplanned so the
walkthrough can say so.

usage:
  walkthrough-plan.py --base URL-or-dir --routes '{"home":"/"}' \\
      --devices '{"phone":390,"desktop":1440}' [--states states.json] \\
      [--planned planned.json] [--out docs/assets/walkthrough.yml] \\
      [--shots-dir docs/assets/shots] [--wait 800] [--json]

planned.json: [{"route": "document", "specifier": "filters-open",
                "javascript": "document.querySelector('#filters').click()"}]
exit 0 written, 2 bad input. Requires Python 3.8+, stdlib only.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path


def capture_name(device: str | None, route: str, specifier: str | None, many_devices: bool) -> str:
	parts = []
	if many_devices and device:
		parts.append(device)
	parts.append(route)
	if specifier:
		parts.append(specifier)
	return "-".join(parts)


def yaml_string(value: str) -> str:
	"""A double-quoted YAML scalar: safe for any JS or path."""
	return json.dumps(value, ensure_ascii=False)


def build(base: str, routes: dict, devices: dict, planned: list, discovered: list, shots_dir: str, wait: int) -> tuple[list[dict], list[dict]]:
	served = base.startswith(("http://", "https://"))
	many = len(devices) > 1
	entries = []
	unplanned = []
	used = set()
	for route, path in routes.items():
		url = base.rstrip("/") + "/" + path.lstrip("/") if served else str(Path(base) / path.lstrip("/"))
		states = [{"specifier": None, "javascript": None, "planned": True}]
		for p in planned:
			if p.get("route") == route:
				states.append({"specifier": p["specifier"], "javascript": p.get("javascript"), "planned": True})
		planned_js = {s["javascript"] for s in states if s["javascript"]}
		for d in discovered:
			if d.get("route") != route or d.get("javascript") in planned_js:
				continue
			planned_js.add(d["javascript"])
			# a trigger found on one device is in the DOM on every device
			states.append({"specifier": d["specifier"], "javascript": d["javascript"], "planned": False})
		for device, width in devices.items():
			for state in states:
				name = capture_name(device, route, state["specifier"], many)
				while name in used:
					name += "-2"
				used.add(name)
				entry = {"output": f"{shots_dir}/{name}.png", "url": url, "width": width, "wait": wait}
				if state["javascript"]:
					entry["javascript"] = state["javascript"]
				if not state["planned"]:
					entry["unplanned"] = True
					unplanned.append({"name": name, "route": route, "device": device, "specifier": state["specifier"]})
				entries.append(entry)
	return entries, unplanned


def to_yaml(entries: list[dict]) -> str:
	lines = ["# Walkthrough captures: every route, every device, every open state.",
			 "# Generated by walkthrough-plan.py; edit here, not in CLI flags."]
	for e in entries:
		if e.get("unplanned"):
			lines.append("# unplanned: found by discovery, not named in the inventory")
		lines.append(f"- output: {yaml_string(e['output'])}")
		lines.append(f"  url: {yaml_string(e['url'])}")
		lines.append(f"  width: {e['width']}")
		lines.append(f"  wait: {e['wait']}")
		if "javascript" in e:
			lines.append(f"  javascript: {yaml_string(e['javascript'])}")
	return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
	parser = argparse.ArgumentParser(description="build the walkthrough shot config")
	parser.add_argument("--base", required=True)
	parser.add_argument("--routes", required=True, help='JSON {slug: path}')
	parser.add_argument("--devices", required=True, help='JSON {name: width}')
	parser.add_argument("--states", default=None, help="open-states.ts output")
	parser.add_argument("--planned", default=None, help="inventory open states JSON")
	parser.add_argument("--out", default=None)
	parser.add_argument("--shots-dir", default="docs/assets/shots")
	parser.add_argument("--wait", type=int, default=800)
	parser.add_argument("--json", action="store_true", help="print the summary as JSON")
	args = parser.parse_args(argv)
	try:
		routes = json.loads(args.routes)
		devices = json.loads(args.devices)
		discovered = json.loads(Path(args.states).read_text())["states"] if args.states else []
		planned = json.loads(Path(args.planned).read_text()) if args.planned else []
	except (OSError, json.JSONDecodeError, KeyError, TypeError) as err:
		print(f"bad input: {err}", file=sys.stderr)
		return 2
	if not isinstance(routes, dict) or not routes or not isinstance(devices, dict) or not devices:
		print("routes and devices must be non-empty JSON objects", file=sys.stderr)
		return 2
	entries, unplanned = build(args.base, routes, devices, planned, discovered, args.shots_dir, args.wait)
	text = to_yaml(entries)
	if args.out:
		Path(args.out).parent.mkdir(parents=True, exist_ok=True)
		Path(args.out).write_text(text)
	else:
		sys.stdout.write(text)
	summary = {"entries": len(entries), "routes": len(routes), "devices": len(devices), "unplanned": unplanned,
			   "out": args.out}
	if args.json:
		print(json.dumps(summary, indent=2))
	elif args.out:
		print(f"wrote {args.out}: {len(entries)} captures, {len(unplanned)} unplanned states")
	return 0


if __name__ == "__main__":
	sys.exit(main(sys.argv[1:]))
